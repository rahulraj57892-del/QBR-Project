/**
 * Retrieves a customer record by its unique identifier.
 * @param customerId - Customer identifier string (e.g., 'cust-apex')
 * @returns Matching Customer record or undefined if not found
 */
export function getMockCustomerById(customerId: string): Customer | undefined {
  return MOCK_CUSTOMERS.find((customer) => customer.id === customerId);
}

/**
 * Retrieves all reporting quarters for a given customer, sorted chronologically.
 * @param customerId - Customer identifier string
 * @returns Array of ReportingQuarter objects sorted by year and quarter ascending
 */
export function getMockQuartersByCustomer(customerId: string): ReportingQuarter[] {
  return MOCK_REPORTING_QUARTERS
    .filter((quarter) => quarter.customerId === customerId)
    .slice()
    .sort((a, b) => {
      if (a.year !== b.year) {
        return a.year - b.year;
      }
      return a.startDate.localeCompare(b.startDate);
    });
}

/**
 * Retrieves KPI records matching both a specific customer and quarter.
 * @param customerId - Customer identifier string
 * @param quarterId - Quarter identifier string
 * @returns Array of KPI records
 */
export function getMockKPIsByQuarter(customerId: string, quarterId: string): KPI[] {
  return MOCK_KPIS.filter(
    (kpi) => kpi.customerId === customerId && kpi.quarterId === quarterId
  );
}

/**
 * Retrieves all KPI records matching a specified functional domain category.
 * @param category - KPICategory union value from `src/types/qbr.ts`
 * @returns Array of matching KPI records across customers and quarters
 */
export function getMockKPIsByCategory(category: KPICategory): KPI[] {
  return MOCK_KPIS.filter((kpi) => kpi.category === category);
}

/**
 * Returns the most recent available quarter for a given customer.
 * @param customerId - Customer identifier string
 * @returns The latest chronological ReportingQuarter or undefined if customer has none
 */
export function getMockLatestQuarter(customerId: string): ReportingQuarter | undefined {
  const quarters = getMockQuartersByCustomer(customerId);
  if (quarters.length === 0) {
    return undefined;
  }
  return quarters[quarters.length - 1];
}
